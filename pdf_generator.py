def generate_markdown_to_pdf(markdown_content, filename_base, is_marathi=False):
    """Converts a partial Markdown string (Question Bank) to PDF."""
    pdf = PDF()
    pdf.header_title = "MAHARASHTRA STATE BOARD"
    pdf.header_subtitle = "Question Bank (2025) - Generated by Learnixis"
    
    base_path = os.path.dirname(os.path.abspath(__file__))
    font_path = os.path.join(base_path, "NotoSansDevanagari-Regular.ttf")
    has_marathi_font = False
    
    latin_path = os.path.join(base_path, "NotoSans-Regular.ttf")
    
    # Logging to debug
    with open("pdf_debug.log", "a") as log:
        log.write(f"\\n--- New Generation ---\\n")
        log.write(f"Subject: {filename_base} | is_marathi: {is_marathi}\\n")
        log.write(f"Base Path: {base_path}\\n")
        log.write(f"Font Path: {font_path} | Exists: {os.path.exists(font_path)}\\n")

    if is_marathi and os.path.exists(font_path):
        try:
            # Register Marathi for all styles
            pdf.add_font("Marathi", "", font_path)
            pdf.add_font("Marathi", "B", font_path)
            pdf.add_font("Marathi", "I", font_path)
            pdf.add_font("Marathi", "BI", font_path)
            has_marathi_font = True
            
            with open("pdf_debug.log", "a") as log:
                log.write("Marathi Font Registered Successfully.\\n")
                
            # Use Latin fallback if available
            if os.path.exists(latin_path):
                pdf.add_font("Latin", "", latin_path)
                pdf.add_font("Latin", "B", latin_path) 
                pdf.set_fallback_fonts(["Latin"])
                
        except Exception as e:
            with open("pdf_debug.log", "a") as log:
                log.write(f"Font loading failed: {str(e)}\\n")
            print(f"Font loading failed: {e}")
    else:
        with open("pdf_debug.log", "a") as log:
            log.write("Skipping Marathi Font registration (Condition Failed).\\n")
            
    pdf.add_page()
    
    # Select Font Family
    font_family = "Marathi" if (is_marathi and has_marathi_font) else "Arial"
    
    lines = markdown_content.split('\n')
    
    for line in lines:
        line = line.strip()
        if not line:
            pdf.ln(2)
            continue
            
        # Clean text specifically for FPDF2 issues
        # Replace escaped underscores
        line = line.replace("\\_", "_")
        # Replace long sequences of underscores with a shorter version to prevent wrapping issues
        while "______" in line:
            line = line.replace("______", "___")
            
        while "______" in line:
            line = line.replace("______", "___")
        
        try:
            # Headers
            if line.startswith('# '):
                pdf.set_font(font_family, "B", 18)
                text = line.replace('# ', '')
                pdf.multi_cell(0, 10, text if has_marathi_font else sanitize(text), 0, 'C')
                pdf.ln(5)
            elif line.startswith('## '):
                pdf.set_font(font_family, "B", 14)
                text = line.replace('## ', '')
                pdf.cell(0, 10, text if has_marathi_font else sanitize(text), 0, 1)
            elif line.startswith('### '):
                pdf.set_font(font_family, "B", 12)
                text = line.replace('### ', '')
                pdf.cell(0, 8, text if has_marathi_font else sanitize(text), 0, 1)
            # List Items
            elif line.startswith('- ') or line.startswith('* '):
                pdf.set_font(font_family, "", 10)
                text = line[2:] # Strip '- '
                # crude bold handling for **text**
                if "**" in text:
                    text = text.replace("**", "") # Remove markers for simplicity in PDF
                    
                pdf.multi_cell(0, 6, f"• {text}" if has_marathi_font else sanitize(f"• {text}"))
            # Numbered List (Simple detection)
            elif line[0].isdigit() and ". " in line[:4]:
                 pdf.set_font(font_family, "", 10)
                 # crude bold handling
                 if "**" in line:
                     line = line.replace("**", "")
                 pdf.multi_cell(0, 6, line if has_marathi_font else sanitize(line))
            # Tables (Very crude fallback)
            elif "|" in line:
                 pdf.set_font(font_family, "I", 8)
                 pdf.cell(0, 5, line if has_marathi_font else sanitize(line), 0, 1)
            # Normal Text
            else:
                pdf.set_font(font_family, "", 10)
                if "**" in line:
                    line = line.replace("**", "")
                pdf.multi_cell(0, 6, line if has_marathi_font else sanitize(line))
        except Exception as e:
            print(f"Error rendering line: {str(e)}")
            # Fallback: Try writing it as simple ASCII if possible, or just skip
            pdf.set_font("Arial", "I", 8)
            pdf.cell(0, 5, "[Error rendering content: Format issue]", 0, 1)
            
    # Save
    output_dir = "downloads"
    if not os.path.exists(output_dir):
        os.makedirs(output_dir)
        
    filename = f"{output_dir}/{filename_base.replace('.md', '.pdf')}"
    pdf.output(filename)
    return filename
