def generate_qa_pdf(chapter_name, questions):
    """Generates a PDF for the Q&A List."""
    pdf = PDF()
    pdf.add_page()
    
    # Header
    pdf.set_font("Arial", "B", 14)
    pdf.cell(0, 10, f"Important Questions: {chapter_name}", 0, 1, 'C')
    pdf.set_font("Arial", "I", 10)
    pdf.cell(0, 10, "Curated by Learnixis AI", 0, 1, 'C')
    pdf.ln(5)
    
    for q in questions:
        # Question
        pdf.set_font("Arial", "B", 11)
        pdf.multi_cell(0, 7, f"Q{q['id']}. {q['question']} ({q['difficulty']})")
        
        # Answer
        pdf.set_font("Arial", "", 10)
        # Handle unicode roughly (replace common issues)
        clean_answer = q['answer'].encode('latin-1', 'replace').decode('latin-1')
        pdf.multi_cell(0, 6, f"Ans: {clean_answer}")
        pdf.ln(3)

    # Ensure directory exists
    output_dir = "downloads"
    if not os.path.exists(output_dir):
        os.makedirs(output_dir)
        
    safe_name = "".join([c for c in chapter_name if c.isalnum() or c in (' ','-','_')]).strip()
    filename = f"{output_dir}/QA_{safe_name}.pdf"
    pdf.output(filename)
    return filename

def sanitize(text, is_marathi=False):
    """Replaces common non-latin-1 characters to prevent PDF generation errors."""
    # If standard sanitize used for Marathi without font, it wipes everything.
    # If font is present, we don't need to strip as aggressively, but FPDF still needs Unicode.
    if is_marathi:
        return text # Trust the font handle to handle it, or it will crash.
        
    replacements = {
        '\u2018': "'", '\u2019': "'",  # Smart quotes
        '\u201c': '"', '\u201d': '"',  # Smart double quotes
        '\u2013': '-', '\u2014': '-',  # Dashes
        '\u2026': '...',               # Ellipsis
        '\u2212': '-',                 # Minus sign
    }
    # First do mapped replacements
    for char, rep in replacements.items():
        text = text.replace(char, rep)
    
    # Then force encode/decode to strip anything else
    return text.encode('latin-1', 'replace').decode('latin-1')

